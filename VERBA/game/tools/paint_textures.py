N=512

def fnoise(n=N, s=13, octaves=4, seed=71):
    r=np.random.default_rng(seed); a=np.zeros((n,n),dtype=np.float32)
    for i in range(octaves):
        grain=r.random((n,n),dtype=np.float32)-0.5
        sigma=max(1, s/(2**i))
        smooth=gaussian_filter(grain,sigma,mode='wrap');smooth/=max(0.01,np.max(abs(smooth)))
        a+=smooth/(1.9**i)
    a=a/np.max(abs(a))
    return a

def save(name, arr):
    im=Image.fromarray(np.uint8(np.clip(arr,0,255)))
    im.save(ROOT/name,optimize=True)
    print(name, im.size)

def tint(base, n, strength=(24,17,12)):
    base=np.array(base,dtype=np.float32); v=np.array(strength,dtype=np.float32)
    return np.clip(base[None,None,:]+n[:,:,None]*v[None,None,:],0,255)

def pbr(name, base, s, seed, strength=(24,18,12), detail=None, normals=True):
    h=fnoise(N,s,4,seed); cc=tint(base,h,strength)
    if detail is not None:
        # Hand-made speckle composition: not an all-over grey noise wash.
        r=np.random.default_rng(seed+20)
        for _ in range(detail):
            x=int(r.integers(0,N)); y=int(r.integers(0,N)); radius=int(r.choice([1,1,2,2,3,4]))
            c=np.array(base)+r.choice([-1,1])*r.uniform(8,34)*np.array([.84,1,.87])
            x1=max(0,x-radius);x2=min(N,x+radius+1);y1=max(0,y-radius);y2=min(N,y+radius+1)
            cc[y1:y2,x1:x2,:]=cc[y1:y2,x1:x2,:]*0.55+c*.45
    save(name+'.png',cc)
    if normals:
        gy,gx=np.gradient(gaussian_filter(h,1.2,mode='wrap'))
        normal=np.stack((-gx*6,-gy*6,np.ones_like(h)),axis=-1)
        normal=normal/np.maximum(np.linalg.norm(normal,axis=-1,keepdims=True),1e-5)
        save(name+'_normal.png',(normal*.5+.5)*255)
        rough=np.clip(205-h*22,170,244)
        save(name+'_roughness.png',rough.astype(np.uint8))

